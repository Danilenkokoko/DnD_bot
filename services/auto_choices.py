def get_optimal_skills_for_class(
    class_name: str,
    available_skills: List[str],
    skill_choices: int,
) -> List[str]:
    """
    Возвращает рекомендованный набор навыков для класса, не превышая лимит.

    Берёт `skill_choices` первых элементов из OPTIMAL_CLASS_SKILLS[class_name],
    отфильтрованных по `available_skills`.

    Args:
        class_name: название класса на русском.
        available_skills: список навыков, доступных классу (из БД).
        skill_choices: количество навыков, которые нужно выбрать.

    Returns:
        Список из ≤ skill_choices названий навыков (на русском).
    """
    if skill_choices <= 0:
        return []
    priorities = OPTIMAL_CLASS_SKILLS.get(class_name, [])
    if not priorities:
        return []
    available_set = set(available_skills) if available_skills else None
    result: List[str] = []
    for skill in priorities:
        if available_set is None or skill in available_set:
            if skill not in result:
                result.append(skill)
        if len(result) >= skill_choices:
            break
    return result


