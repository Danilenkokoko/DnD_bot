def generate_personality_traits(seed: Optional[int] = None) -> Dict[str, str]:
    """
    Возвращает словарь {personality_trait, ideal, bond, flaw} —
    случайные значения из общего пула. Используется как авто-дефолт при
    сохранении персонажа, если игрок не ввёл свои.

    Args:
        seed: опциональный seed для random.choice (для тестов).
    """
    import random as _random
    rng = _random.Random(seed)
    return {
        "personality_trait": rng.choice(PERSONALITY_TRAITS_POOL),
        "ideal":             rng.choice(IDEALS_POOL),
        "bond":              rng.choice(BONDS_POOL),
        "flaw":              rng.choice(FLAWS_POOL),
    }


def recommend_fighting_style(weapon_name: Optional[str]) -> str:
    """
    Возвращает рекомендуемое имя Fighting Style по названию оружия.

    Эвристика устойчивая, но не идеальная — она опирается на ключевые слова
    в названии. Для одноручного оружия со щитом дефолтная рекомендация —
    «Оборона» (+1 AC), это самый безопасный универсальный выбор для
    Воин/Паладин на 1 уровне.

    Args:
        weapon_name: имя оружия из selected_weapon (может быть None).

    Returns:
        Имя Fighting Style точно как в `fighting_styles.name` в БД.
    """
    if not weapon_name:
        return _DEFAULT_FIGHTING_STYLE
    name_lower = weapon_name.lower()
    for keywords, style in _WEAPON_KEYWORD_TO_STYLE:
        if any(kw in name_lower for kw in keywords):
            return style
    return _DEFAULT_FIGHTING_STYLE
