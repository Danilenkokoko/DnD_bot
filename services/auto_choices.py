def get_default_languages_for_background(background_name: str) -> List[str]:
    """Возвращает список языков (Общий + 2 от предыстории)."""
    bg_langs = BACKGROUND_DEFAULT_LANGUAGES.get(
        background_name, list(DEFAULT_BACKGROUND_LANGUAGES)
    )
    result = [COMMON_LANGUAGE]
    for lang in bg_langs:
        if lang not in result:
            result.append(lang)
    return result


