# 3. ИНСТРУМЕНТЫ ПРЕДЫСТОРИИ
# =============================================================================
def parse_background_tools(tools_str: str) -> List[str]:
    """Превращает строку инструментов предыстории в список названий."""
    if not tools_str or tools_str.strip().lower() in ("нет", "—", "-", ""):
        return []
    parts = [p.strip() for p in tools_str.replace(";", ",").split(",")]
    return [p for p in parts if p and p.lower() not in ("и", "или", "а", "один", "набор")]


