WEAPON_MASTERY_CLASSES = {"Воин", "Варвар", "Плут", "Паладин", "Следопыт"}
WEAPON_MASTERY_LIMITS = {
    "Воин": 3,
    "Варвар": 2,
    "Плут": 2,
    "Паладин": 2,
    "Следопыт": 2,
}


def class_has_weapon_mastery(class_name: str) -> bool:
    """True, если класс получает мастерство оружия на 1 уровне."""
    return class_name in WEAPON_MASTERY_CLASSES


def get_weapon_mastery_limit(class_name: str) -> int:
    """Возвращает максимальное число приёмов оружия для класса на 1 уровне."""
    return WEAPON_MASTERY_LIMITS.get(class_name, 0)


