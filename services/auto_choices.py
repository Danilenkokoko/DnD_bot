_WEAPON_KEYWORD_TO_STYLE = [
    (("лук", "арбалет"), "Стрельба"),
    (("двуручн", "глеф", "алебард", "пик", "секира"), "Сражение большим оружием"),
    (("кинжал", "ятаган", "скимитар"), "Сражение двумя оружиями"),
    (("метательн", "дротик"), "Сражение метательным оружием"),
]
_DEFAULT_FIGHTING_STYLE = "Оборона"


def recommend_fighting_style(weapon_name: Optional[str]) -> str:
    """Возвращает рекомендуемый боевой стиль по названию оружия."""
    if not weapon_name:
        return _DEFAULT_FIGHTING_STYLE
    name_lower = weapon_name.lower()
    for keywords, style in _WEAPON_KEYWORD_TO_STYLE:
        if any(kw in name_lower for kw in keywords):
            return style
    return _DEFAULT_FIGHTING_STYLE


