def parse_background_tools(tools_str: str) -> List[str]:
    """
    В таблице `backgrounds` поле `tools` хранится как строка
    (например, "Музыкальный инструмент" или "Инструменты каллиграфа").
    По RAW предыстория даёт владение одним инструментом. Эта функция
    превращает строку в список (поддерживая случай нескольких инструментов
    через запятую).

    Args:
        tools_str: исходная строка из БД.

    Returns:
        Список названий инструментов; пустой список, если ничего не задано.
    """
    if not tools_str:
        return []
    parts = [p.strip() for p in tools_str.split(",") if p.strip()]
    # Отсекаем явные «нет» / «—»
    parts = [p for p in parts if p.lower() not in ("нет", "—", "-", "n/a")]
    return parts


